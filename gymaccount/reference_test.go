type enrollmentReference struct {
	Name                  string                         `json:"name"`
	FixtureName           string                         `json:"fixture_name"`
	TestOnlyPrivateKey    string                         `json:"test_only_private_key"`
	Challenge             gymaccount.EnrollmentChallenge `json:"challenge"`
	Authorization         gymaccount.Authorization       `json:"authorization"`
	ExpectedPayload       string                         `json:"expected_payload"`
	ExpectedDigest        string                         `json:"expected_digest"`
	InvalidHighSSignature string                         `json:"invalid_high_s_signature"`
}

func enrollmentReferences(t *testing.T) []enrollmentReference {
	t.Helper()
	raw, err := os.ReadFile("testdata/enrollment_v1.json")
	if err != nil {
		t.Fatal(err)
	}
	var file struct {
		FixtureOnly bool                  `json:"fixture_only"`
		Cases       []enrollmentReference `json:"cases"`
	}
	decoder := json.NewDecoder(bytes.NewReader(raw))
	decoder.DisallowUnknownFields()
	if err := decoder.Decode(&file); err != nil {
		t.Fatal(err)
	}
	if !file.FixtureOnly || len(file.Cases) != 4 {
		t.Fatal("expected four explicitly public enrollment fixture cases")
	}
	return file.Cases
}

func referenceHex(t *testing.T, value string) []byte {
	t.Helper()
	raw, err := hex.DecodeString(value)
	if err != nil {
		t.Fatal(err)
	}
	return raw
}

// These values were generated by independent Python BIP39/BIP32/secp256k1
// arithmetic before inspecting the Go implementation. Both private scalars
// are published test inputs; this test never opens a wallet or private file.
func TestReferenceEnrollmentVectors(t *testing.T) {
	for _, fixture := range enrollmentReferences(t) {
		t.Run(fixture.Name, func(t *testing.T) {
			payload := referenceHex(t, fixture.ExpectedPayload)
			if !bytes.HasPrefix(payload, []byte("SLUG account enrollment\x00v1\x00")) {
				t.Fatal("independent payload lost its action domain")
			}
			payloadDigest := sha256.Sum256(payload)
			if hex.EncodeToString(payloadDigest[:]) != fixture.ExpectedDigest {
				t.Fatal("independent payload/digest mismatch")
			}
			digest, err := gymaccount.ChallengeDigest(fixture.Challenge)
			if err != nil || digest != payloadDigest {
				t.Fatalf("digest differs from independent binary payload: %x, %v", digest, err)
			}
			if err := gymaccount.VerifyAuthorization(fixture.Challenge, fixture.Authorization); err != nil {
				t.Fatalf("independent signature rejected: %v", err)
			}
			key, _ := btcec.PrivKeyFromBytes(referenceHex(t, fixture.TestOnlyPrivateKey))
			defer key.Zero()
			if hex.EncodeToString(key.PubKey().SerializeCompressed()) != fixture.Challenge.GymPublicKey {
				t.Fatal("public fixture scalar does not match independently derived gym")
			}
			authorization, err := gymaccount.SignChallenge(fixture.Challenge, key)
			if err != nil || authorization != fixture.Authorization {
				t.Fatalf("signature differs from independent RFC6979/DER vector: %+v, %v", authorization, err)
			}
			if err := gymaccount.ValidateFixtureIdentity(fixture.Challenge.RootPublicKey,
				fixture.Challenge.GymPublicKey, fixture.Challenge.GymID); err != nil {
				t.Fatalf("published independent identity refused: %v", err)
			}
		})
	}
}

func TestReferenceEnrollmentBindsEveryField(t *testing.T) {
	fixtures := enrollmentReferences(t)
	first, other := fixtures[0], fixtures[2]
	mutations := []struct {
		name string
		edit func(*gymaccount.EnrollmentChallenge)
	}{
		{"version", func(c *gymaccount.EnrollmentChallenge) { c.Version++ }},
		{"authority", func(c *gymaccount.EnrollmentChallenge) { c.AuthorityID = strings.Repeat("01", 32) }},
		{"account", func(c *gymaccount.EnrollmentChallenge) { c.AccountID = other.Challenge.AccountID }},
		{"principal", func(c *gymaccount.EnrollmentChallenge) { c.PrincipalID = other.Challenge.PrincipalID }},
		{"challenge", func(c *gymaccount.EnrollmentChallenge) { c.ChallengeID = fixtures[1].Challenge.ChallengeID }},
		{"generation", func(c *gymaccount.EnrollmentChallenge) { c.Generation++ }},
		{"action", func(c *gymaccount.EnrollmentChallenge) { c.Action = "recover" }},
		{"network", func(c *gymaccount.EnrollmentChallenge) { c.Network++ }},
		{"genesis", func(c *gymaccount.EnrollmentChallenge) { c.Genesis = strings.Repeat("02", 32) }},
		{"profile", func(c *gymaccount.EnrollmentChallenge) { c.Profile += "-other" }},
		{"root", func(c *gymaccount.EnrollmentChallenge) { c.RootPublicKey = other.Challenge.RootPublicKey }},
		{"gym-public-key", func(c *gymaccount.EnrollmentChallenge) { c.GymPublicKey = other.Challenge.GymPublicKey }},
		{"gym-id", func(c *gymaccount.EnrollmentChallenge) { c.GymID = other.Challenge.GymID }},
		{"issued", func(c *gymaccount.EnrollmentChallenge) { c.IssuedAtMS++ }},
		{"expiry", func(c *gymaccount.EnrollmentChallenge) { c.ExpiresAtMS++ }},
	}
	for _, mutation := range mutations {
		t.Run(mutation.name, func(t *testing.T) {
			challenge := first.Challenge
			mutation.edit(&challenge)
			if err := gymaccount.VerifyAuthorization(challenge, first.Authorization); err == nil {
				t.Fatal("signed field could be changed without invalidating authorization")
			}
		})
	}
	for i := range fixtures {
		for j := range fixtures {
			if i == j {
				continue
			}
			if err := gymaccount.VerifyAuthorization(fixtures[i].Challenge, fixtures[j].Authorization); err == nil {
				t.Fatalf("authorization transplanted from %s into %s", fixtures[j].Name, fixtures[i].Name)
			}
		}
	}
}

func TestReferenceEnrollmentCanonicalAndSeparated(t *testing.T) {
	fixture := enrollmentReferences(t)[0]
	digest := referenceHex(t, fixture.ExpectedDigest)
	key, public := btcec.PrivKeyFromBytes(referenceHex(t, fixture.TestOnlyPrivateKey))
	defer key.Zero()
	high := referenceHex(t, fixture.InvalidHighSSignature)
	signature, err := ecdsa.ParseDERSignature(high)
	if err != nil || !signature.Verify(digest, public) {
		t.Fatal("high-S negative fixture must first be mathematically valid ECDSA")
	}
	mutations := []struct {
		name string
		edit func(*gymaccount.Authorization)
	}{
		{"high-s", func(a *gymaccount.Authorization) { a.Signature = fixture.InvalidHighSSignature }},
		{"trailing-der", func(a *gymaccount.Authorization) { a.Signature += "00" }},
		{"uppercase-der", func(a *gymaccount.Authorization) { a.Signature = strings.ToUpper(a.Signature) }},
		{"uppercase-public", func(a *gymaccount.Authorization) { a.PublicKey = strings.ToUpper(a.PublicKey) }},
		{"uncompressed-public", func(a *gymaccount.Authorization) { a.PublicKey = hex.EncodeToString(public.SerializeUncompressed()) }},
		{"authorization-version", func(a *gymaccount.Authorization) { a.Version++ }},
	}
	for _, mutation := range mutations {
		t.Run(mutation.name, func(t *testing.T) {
			authorization := fixture.Authorization
			mutation.edit(&authorization)
			if err := gymaccount.VerifyAuthorization(fixture.Challenge, authorization); err == nil {
				t.Fatal("noncanonical authorization accepted")
			}
		})
	}
	// Use the same real fixture key and identical body with a distinct action
	// domain. This is a valid ECDSA signature, but not account authorization.
	payload := referenceHex(t, fixture.ExpectedPayload)
	body := bytes.TrimPrefix(payload, []byte("SLUG account enrollment\x00v1\x00"))
	wrongDigest := sha256.Sum256(append([]byte("SLUG prospect admission\x00v2\x00"), body...))
	wrongSignature := ecdsa.Sign(key, wrongDigest[:])
	if !wrongSignature.Verify(wrongDigest[:], public) {
		t.Fatal("cross-domain negative signature is not valid in its own domain")
	}
	wrong := fixture.Authorization
	wrong.Signature = hex.EncodeToString(wrongSignature.Serialize())
	if err := gymaccount.VerifyAuthorization(fixture.Challenge, wrong); err == nil {
		t.Fatal("different action domain authorized account enrollment")
	}
}

func TestReferenceEnrollmentRootBindingRequiresFixturePolicy(t *testing.T) {
	fixtures := enrollmentReferences(t)
	challenge := fixtures[0].Challenge
	challenge.RootPublicKey = fixtures[2].Challenge.RootPublicKey
	key, _ := btcec.PrivKeyFromBytes(referenceHex(t, fixtures[0].TestOnlyPrivateKey))
	defer key.Zero()
	// A signature can bind a claimed root to a gym key, but cannot prove a
	// hardened derivation from that root. Keep this distinction explicit.
	authorization, err := gymaccount.SignChallenge(challenge, key)
	if err != nil || gymaccount.VerifyAuthorization(challenge, authorization) != nil {
		t.Fatalf("mathematically well-formed mixed identity could not be signed: %v", err)
	}
	if err := gymaccount.ValidateFixtureIdentity(challenge.RootPublicKey, challenge.GymPublicKey, challenge.GymID); err == nil {
		t.Fatal("fixture policy accepted a root/gym mixture despite missing derivation evidence")
	}
}
