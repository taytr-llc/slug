// Published HTTP token shape translated to the same original fixture session.
// This does not grant a production account, wallet, or credential capability.
type retainedAdmissionDeliverySessions string

func (s retainedAdmissionDeliverySessions) WithSession(ctx context.Context, token string, fn func(string, func() error) error) error {
	if token != strings.Repeat("ab", 32) {
		return errors.New("unexpected published admission token")
	}
	return opLiveSessions(s).WithSession(ctx, "published-live-round-session", fn)
}

// The original node's exact current-parent check is reused. The admission
// observation is deliberately controlled, but accepts only the original work's
// real normal-PoW proof/hash after the registry's own verification. No DTO is
// installed as a record, and no signing or pool credit comes from this node.
type retainedAdmissionDeliveryNode struct {
	original *opLiveNode
	work     poolshare.MiningWork
	proofs   map[string]prospectwork.ShareCheck
	checks   int
}

func (n *retainedAdmissionDeliveryNode) Resolve(context.Context, prospectnode.Policy) (prospect.Context, error) {
	return prospect.Context{}, errors.New("admission-only owner cannot issue work")
}
func (n *retainedAdmissionDeliveryNode) RecheckContext(ctx context.Context, c prospect.Context) error {
	return n.original.RecheckContext(ctx, c)
}
func (n *retainedAdmissionDeliveryNode) RecheckAdmission(ctx context.Context, c prospect.Context, proof prospect.Proof, verified prospect.Verified) (string, error) {
	n.checks++
	v, ok := n.proofs[verified.WorkHash]
	if !ok || v.Candidate == nil || !v.Prospect || v.Block || c != n.work.Job.Context || !reflect.DeepEqual(proof, v.Candidate.Proof) || proof.JobID != n.work.Job.ID || verified.GymID != n.work.Job.GymID || verified.ParentHash != c.ParentHash || verified.ParentHeight != c.ParentHeight {
		return "", errors.New("not exact retained original-job proof")
	}
	if e := n.original.RecheckContext(ctx, c); e != nil {
		return "", e
	}
	return "current-parent", nil
}

func selectRetainedAdmissionDelivery(t *testing.T, h *intakeBusyHarness, node *retainedAdmissionDeliveryNode) {
	t.Helper()
	server, e := prospectservice.NewPausedDailyFencedManifestAdmissionServer(prospectservice.ManifestServerConfig{Version: 3, Listen: "127.0.0.1:0", AuthorityPin: h.source.AuthorityPin, Clients: []prospectservice.Credential{}, MaxJobs: h.source.MaxWorks, MaxRecords: uint64(opSetupTestReference(t).Positives[0].Setup.Authority.Limits.Admissions)}, h.source.Policy, node, h.issuer, retainedAdmissionDeliverySessions(h.publicKey))
	if e != nil {
		t.Fatal(e)
	}
	h.control.daily = true
	h.control.admissionServer = server
}

func retainedAdmissionRequest(t *testing.T, ctx context.Context, server *prospectservice.ManifestServer, proof prospect.Proof, auth gymauth.Authorization) prospectservice.ManifestAdmissionResult {
	t.Helper()
	body, e := json.Marshal(struct {
		Proof         prospect.Proof        `json:"proof"`
		Authorization gymauth.Authorization `json:"authorization"`
	}{proof, auth})
	if e != nil {
		t.Fatal(e)
	}
	request := httptest.NewRequest(http.MethodPost, "/v3/admissions", bytes.NewReader(body)).WithContext(ctx)
	request.Host = "127.0.0.1:12345"
	request.Header.Set("Content-Type", "application/json")
	request.Header.Set("Authorization", "Bearer "+strings.Repeat("ab", 32))
	response := httptest.NewRecorder()
	server.ServeHTTP(response, request) // synchronous: the original handler joins before return
	var result prospectservice.ManifestAdmissionResult
	if response.Code != http.StatusOK || json.Unmarshal(response.Body.Bytes(), &result) != nil || result.Version != 3 || result.Authentication != "gym-key-control" || result.BirthRule != "job-issuance" {
		t.Fatal("original authenticated admission", response.Code, response.Body.String())
	}
	return result
}

// Extends the full-source physical-reopen test while its original signed A is
// pending. The published incrementing256 scalar is an INPUT from independent
// gymaccount/testdata/enrollment_v1.json, not an expected signature generated by
// the product. Both proofs are dynamically constructed for the original fresh
// job, using the already pinned normal template and bounded CheckNonce search.
func exerciseRetainedAdmissionDelivery(t *testing.T, h *intakeBusyHarness, node *retainedAdmissionDeliveryNode, work poolshare.MiningWork, first prospectwork.ShareCheck) {
	t.Helper()
	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()
	if first.Candidate == nil || !first.Prospect || first.Block || work.Job.PublicKey != h.publicKey {
		t.Fatal("original retained proof input")
	}
	raw, e := hex.DecodeString("948996ecaa9fa9707693267d6d4abefe0b5fb28b6ebae34f542e106244d254e1")
	if e != nil {
		t.Fatal(e)
	}
	key, _ := btcec.PrivKeyFromBytes(raw)
	clear(raw)
	defer key.Zero()
	if hex.EncodeToString(key.PubKey().SerializeCompressed()) != h.publicKey {
		t.Fatal("published original gym key mismatch")
	}
	profile, e := registry.NewOperatorProfile(opSetupTestReference(t).Positives[0].Setup.Authority)
	if e != nil {
		t.Fatal(e)
	}
	publication, e := h.issuer.OperatorPublication(profile)
	if e != nil {
		t.Fatal(e)
	}
	// This is the existing borrowed publisher. Its original Runtime cleanup
	// closes it before the issuer; this helper neither replaces nor closes it.
	before, e := publication.Status(ctx)
	if e != nil || before.AcceptedSequence != 0 || before.SignedAdmissionSequence != 0 || before.PublicEvidencePending {
		t.Fatal("initial original publication", before, e)
	}
	info, e := h.issuer.Info()
	if e != nil || info.Records != 0 || info.Jobs != 2 {
		t.Fatal("initial original jobs/records", info, e)
	}
	auth, e := gymauth.SignAdmission(work.Job.Context, first.Candidate.Proof, key)
	if e != nil {
		t.Fatal(e)
	}
	result := retainedAdmissionRequest(t, ctx, h.control.admissionServer, first.Candidate.Proof, auth)
	r := result.Record
	if !result.Inserted || !result.CurrentNodeChecked || result.ContextSource != "trusted-node-snapshot" || r.Sequence != 1 || r.Job != work.Job || r.Context != work.Job.Context || !reflect.DeepEqual(r.Proof, first.Candidate.Proof) || r.Authorization != auth || r.Verified.WorkHash != first.WorkHash || r.Verified.GymID != h.gym || r.Birth.BornAtMS != work.Job.IssuedAtMS || r.Birth.AcceptedAtMS < work.Job.IssuedAtMS || r.Birth.AcceptedAtMS >= work.Job.ExpiresAtMS || r.Eligibility.Source != "current-parent" || node.checks != 1 {
		t.Fatal("first original admission differs", result, node.checks)
	}
	stored, e := h.issuer.GetManifestAdmission(r.Verified.ProspectID)
	if e != nil || !reflect.DeepEqual(stored, r) {
		t.Fatal("original durable record differs", e)
	}
	one, e := publication.Status(ctx)
	if e != nil || one.AcceptedSequence != 1 || one.SignedAdmissionSequence != 0 || one.PublicationSequence != before.PublicationSequence || !one.PublicEvidencePending {
		t.Fatal("one original unsigned admission/outbox", one, e)
	}

	// A second distinct valid proof of the SAME already-issued job is legal.
	// It is not submitted as a new pool share; the source remains exactly2/2.
	prepared, e := prospectwork.PrepareManifestWork(work.Job, work.Template, h.source.PayoutAddress, 0, h.source.PoolTarget)
	if e != nil {
		t.Fatal(e)
	}
	var second prospectwork.ShareCheck
	for nonce := uint32(0); nonce < 64; nonce++ {
		if nonce == first.Nonce {
			continue
		}
		v, e := prepared.CheckNonce(ctx, nonce)
		if e != nil {
			t.Fatal(e)
		}
		if v.Prospect && !v.Block && v.Candidate != nil {
			second = v
			break
		}
	}
	if second.Candidate == nil || second.WorkHash == first.WorkHash {
		t.Fatal("bounded distinct normal proof search exhausted")
	}
	node.proofs[second.WorkHash] = second
	secondAuth, e := gymauth.SignAdmission(work.Job.Context, second.Candidate.Proof, key)
	if e != nil {
		t.Fatal(e)
	}
	other := retainedAdmissionRequest(t, ctx, h.control.admissionServer, second.Candidate.Proof, secondAuth)
	if !other.Inserted || !other.CurrentNodeChecked || other.ContextSource != "trusted-node-snapshot" || other.Record.Sequence != 2 || other.Record.Job != work.Job || other.Record.Context != work.Job.Context || other.Record.Birth.BornAtMS != work.Job.IssuedAtMS || other.Record.Birth.AcceptedAtMS < work.Job.IssuedAtMS || other.Record.Birth.AcceptedAtMS >= work.Job.ExpiresAtMS || other.Record.Verified.ProspectID == r.Verified.ProspectID || other.Record.Verified.WorkHash != second.WorkHash || !reflect.DeepEqual(other.Record.Proof, second.Candidate.Proof) || other.Record.Authorization != secondAuth || other.Record.Eligibility.Source != "current-parent" || node.checks != 2 {
		t.Fatal("same original job was limited to one proof", other)
	}
	recovered := retainedAdmissionRequest(t, ctx, h.control.admissionServer, first.Candidate.Proof, auth)
	if recovered.Inserted || recovered.CurrentNodeChecked || recovered.ContextSource != "historical-receipt" || !reflect.DeepEqual(recovered.Record, r) || node.checks != 2 {
		t.Fatal("first original historical receipt changed", recovered)
	}
	after, e := h.issuer.Info()
	if e != nil || after.Jobs != info.Jobs || after.Records != 2 {
		t.Fatal("admission replaced jobs or duplicated records", after, e)
	}
	pub, e := publication.Status(ctx)
	if e != nil || pub.AcceptedSequence != 2 || pub.SignedAdmissionSequence != 0 || pub.PublicationSequence != before.PublicationSequence || !pub.PublicEvidencePending {
		t.Fatal("exact unsigned original outbox delta", pub, e)
	}
	status, e := h.control.intake.Status(ctx)
	if e != nil || status.Mode != "draining" || status.Maximum != 2 || status.Submissions != 2 || status.Accepted != 2 {
		t.Fatal("admission changed source accounting", status, e)
	}
	retainedAdmissionModes(t, h, "draining", "enabled")
}
